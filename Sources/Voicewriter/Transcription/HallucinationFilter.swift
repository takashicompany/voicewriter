import Foundation

/// ハルシネーション対策(多層防御)の第5層(最終防衛線): whisper.cppの出力全体が
/// 既知の無音ハルシネーション定型句(完全一致・句読点等の差異を除いたほぼ一致)のみで
/// 構成される場合に、その出力を「無音扱い」として棄却する。
///
/// whisper(.cpp)は学習データにYouTube動画の字幕が含まれるため、無音/低品質な音声区間で
/// 「ご視聴ありがとうございました」のような動画終端の定型句を無関係に出力してしまうことが
/// 広く報告されている(一次情報: https://github.com/ggml-org/whisper.cpp/issues/1724 )。
/// 日本語話者からの同種の報告は https://github.com/amicalhq/amical/issues/71 にも見られる。
///
/// **重要**: 発話の一部として実際にこれらの語句を言った場合を誤って棄却しないよう、
/// 「出力の全体(句読点等を正規化した上で)がこの語句だけ」の場合に限定して判定する。
/// 文中の一部に含まれるだけ(例: 「今日の会議は以上です。ご視聴ありがとうございました。」のように
/// 本当にそう言った場合)は対象外とし、部分一致では棄却しない。
///
/// **語句リストの選定方針(改訂)**: 当初は`amicalhq/amical#71`で報告された「ありがとうございました」
/// 「おやすみなさい」のような汎用的な挨拶句も含めていたが、これらは単独でも正当なディクテーション
/// として十分成立しうる(例: チャット相手への返信として「ありがとうございます」とだけ音声入力する、
/// という普通の使い方がある)。「出力全体が完全一致する場合に限定する」という設計だけでは、
/// この種の短い定型的な返信全体を毎回誤って棄却してしまうリスクを避けられないため、
/// 汎用的な挨拶句は語句リストから除外し、**動画(YouTube等)固有性が高く、通常の会話・チャットの
/// 返信としては使われにくい句のみ**(「ご視聴/ご清聴/ご静聴ありがとうございました」系、
/// 「チャンネル登録よろしくお願いします」系)に限定した。
///
/// 参考にした先行実装(値・方針のみを参考にし、コードの引用・移植は行っていない):
/// - VoiceInk(https://github.com/Beingpax/VoiceInk ): プロンプトエコー検出(完全一致/部分一致/
///   80%超の重複)と、`no_speech_prob`が60%を超えるセグメントを棄却する二段構えのフィルタを持つ。
///   本実装の`WhisperCppEngine`側セグメントフィルタ(no_speech_prob >= 0.6)はこの閾値を踏襲した。
/// - 一般的なコミュニティの知見(Qiita「Whisper API 無音時に『ご視聴ありがとうございました』」等):
///   句読点の有無に関わらず同一のハルシネーションが出るため、比較前に句読点を除去する必要がある、
///   という指摘があり、本実装の`normalize`もこれを踏まえている。
enum HallucinationFilter {
    /// 既知の無音ハルシネーション定型句(句読点抜きの正規形で列挙)。
    /// whisper.cppの学習データがYouTube動画由来であることに起因し、動画の終わりに挿入される
    /// 定型的な挨拶・呼びかけが典型パターンとして報告されている。
    ///
    /// **汎用的な挨拶句(「ありがとうございました」「おやすみなさい」等)は意図的に含めていない**。
    /// これらは単独でも正当なディクテーション(例: チャットへの短い返信)として成立しうるため、
    /// 動画(YouTube等)固有性が高く通常の会話では使われにくい句のみに限定している
    /// (上記クラスコメント「語句リストの選定方針(改訂)」参照)。
    static let knownPhrases: [String] = [
        "ご視聴ありがとうございました",
        "ご視聴ありがとうございます",
        "ご視聴いただきありがとうございました",
        "最後までご視聴いただきありがとうございました",
        "ご清聴ありがとうございました",
        "ご清聴ありがとうございます",
        "ご静聴ありがとうございます",
        "ご静聴ありがとうございました",
        "チャンネル登録",
        "チャンネル登録をお願いします",
        "チャンネル登録よろしくお願いします",
        "高評価とチャンネル登録よろしくお願いします",
        "字幕視聴ありがとうございました",
    ]

    /// 出力全体が既知の定型句(完全一致・句読点等を除いたほぼ一致)のみで構成される場合はtrueを返す。
    static func isLikelyHallucination(_ text: String) -> Bool {
        let normalized = normalize(text)
        guard !normalized.isEmpty else { return false }
        return knownPhrases.contains { normalize($0) == normalized }
    }

    /// 句読点・空白・改行・感嘆符等の差異を吸収するための正規化。
    /// whisper.cppは同一のハルシネーションでも句読点の有無・種類がまちまちに出力することがあるため、
    /// 比較前に取り除く(全角・半角の代表的な区切り記号を対象とする)。
    ///
    /// まず`precomposedStringWithCompatibilityMapping`(Unicode互換等価分解+正規化合成、
    /// いわゆるNFKC相当)を適用し、全角/半角英数字や一部の合字・互換文字の表記揺れを
    /// 吸収してから句読点除去を行う。
    private static func normalize(_ text: String) -> String {
        let punctuation: Set<Character> = [
            "。", "、", "！", "!", "?", "?", ".", ",", "・",
            " ", "\u{3000}", "\n", "\t", "\r", "…", "「", "」", "『", "』"
        ]
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        let nfkc = trimmed.precomposedStringWithCompatibilityMapping
        return String(nfkc.filter { !punctuation.contains($0) })
    }
}
